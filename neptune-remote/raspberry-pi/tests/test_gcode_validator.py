def test_a_file_without_g90_or_g91_is_blocked():
    report = analyse(HEADER + "M83\nG28\nG1 X10 Y10 F1800\n")
    assert report.verdict is GCodeVerdict.BLOCKED
    assert any(i.code == "no_positioning_mode" for i in report.errors)


def test_a_file_that_never_homes_is_blocked():
    report = analyse(HEADER + "G90\nM83\nM104 S210\nG1 X10 Y10 F1800\n")
    assert report.verdict is GCodeVerdict.BLOCKED
    assert any(i.code == "no_homing" for i in report.errors)


def test_a_missing_extrusion_mode_warns():
    report = analyse(HEADER + "G90\nM104 S210\nG28\nG1 X10 Y10 F1800\n")
    assert any(i.code == "no_extrusion_mode" for i in report.warnings)


def test_a_file_with_no_motion_is_blocked():
    report = analyse(HEADER + "G90\nM83\nG28\nM104 S210\n")
    assert report.verdict is GCodeVerdict.BLOCKED
    assert any(i.code == "no_motion" for i in report.errors)


