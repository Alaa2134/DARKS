"""Static G-code analysis.

This module exists because a mismatched slicer profile once produced a print in
the wrong physical location. Every test here is a shape of that failure.

Note what is *not* tested: any ability to rewrite G-code. The analyser has no
such function - it reads and reports, and nothing more.
"""

from __future__ import annotations

import pytest

from app.gcode.validator import GCodeVerdict, analyse_gcode, analyse_gcode_file
from app.klipper.model import parse_config

CONFIG = parse_config(
    """
[printer]
kinematics: cartesian
max_velocity: 300
max_accel: 3000

[stepper_x]
position_min: -3
position_max: 330

[stepper_y]
position_min: -8
position_max: 330

[stepper_z]
position_min: 0
position_max: 410

[extruder]
nozzle_diameter: 0.4
"""
)

GOLDEN = ["Neptune3Plus 0.20 Standard"]

HEADER = """; generated by PrusaSlicer 2.8.1+linux on 2026-01-01 at 10:00:00
; layer_height = 0.2
; first_layer_height = 0.25
; nozzle_diameter = 0.4
; print_settings_id = Neptune3Plus 0.20 Standard
; filament_settings_id = Generic PLA
"""

BODY = """G90
M83
M104 S210
M140 S60
G28
M204 S3000
G1 X10 Y10 Z0.2 F1800
G1 X300 Y300 E5 F3000
"""


def good(extra: str = "", header: str = HEADER, body: str = BODY) -> str:
    return header + body + extra


def analyse(text: str, **kwargs):
    kwargs.setdefault("config", CONFIG)
    kwargs.setdefault("golden_profiles", GOLDEN)
    return analyse_gcode(text, **kwargs)


# --------------------------------------------------------------------------- #
# The happy path
# --------------------------------------------------------------------------- #


def test_a_clean_prusaslicer_file_is_safe():
    report = analyse(good())
    assert report.verdict is GCodeVerdict.SAFE
    assert report.issues == []
    assert report.slicer == "PrusaSlicer"
    assert report.slicer_version.startswith("2.8.1")
    assert report.verified_profile is True
    assert report.profile_status == "golden"


def test_metadata_is_extracted():
    report = analyse(good())
    assert report.layer_height == 0.2
    assert report.first_layer_height == 0.25
    assert report.nozzle_diameter == 0.4
    assert report.profile_name == "Neptune3Plus 0.20 Standard"
    assert report.filament == "Generic PLA"


def test_bounds_are_measured():
    report = analyse(good())
    assert report.bounds.min_x == 10.0
    assert report.bounds.max_x == 300.0
    assert report.bounds.max_z == 0.2


# --------------------------------------------------------------------------- #
# Build volume - checked against the LIVE config
# --------------------------------------------------------------------------- #


def test_a_move_beyond_the_configured_maximum_is_blocked():
    report = analyse(good("G1 X400 Y10\n"))
    assert report.verdict is GCodeVerdict.BLOCKED
    assert any(i.code == "outside_build_volume" for i in report.errors)


def test_a_move_below_the_configured_minimum_is_blocked():
    report = analyse(good("G1 X-50 Y10\n"))
    assert report.verdict is GCodeVerdict.BLOCKED


def test_bounds_are_judged_by_the_live_config_not_the_printer_model():
    """A 330 mm move is fine on this printer, and out of range on a smaller one."""
    small = parse_config(
        "[printer]\n[stepper_x]\nposition_min: 0\nposition_max: 220\n"
        "[stepper_y]\nposition_min: 0\nposition_max: 220\n"
        "[stepper_z]\nposition_min: 0\nposition_max: 250\n"
    )
    assert analyse(good()).verdict is GCodeVerdict.SAFE
    report = analyse_gcode(good(), config=small, golden_profiles=GOLDEN)
    assert report.verdict is GCodeVerdict.BLOCKED


def test_without_a_live_config_the_volume_check_is_reported_as_skipped():
    report = analyse_gcode(good(), config=None, golden_profiles=GOLDEN)
    assert any(i.code == "limits_unknown" for i in report.issues)
    assert report.verdict is GCodeVerdict.WARNING


def test_relative_moves_are_resolved_to_absolute_positions():
    text = HEADER + "G90\nM83\nG28\nG1 X10 Y10\nG91\nG1 X100\nG1 X100\n"
    report = analyse(text)
    # 10 + 100 + 100 = 210, not three separate 100s.
    assert report.bounds.max_x == pytest.approx(210.0)


def test_g92_origin_shifts_are_accounted_for():
    """A G92 that redefines the origin must not hide a move off the bed."""
    text = HEADER + "G90\nM83\nG28\nG1 X300 Y10\nG92 X0\nG1 X100\n"
    report = analyse(text)
    # After G92 X0 at machine X=300, "X100" is really machine X=400.
    assert report.bounds.max_x == pytest.approx(400.0)
    assert report.verdict is GCodeVerdict.BLOCKED


