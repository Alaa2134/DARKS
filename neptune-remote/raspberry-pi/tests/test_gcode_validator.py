def test_a_missing_file_is_an_error_not_a_crash(tmp_path):
    report = analyse_gcode_file(tmp_path / "nope.gcode", config=CONFIG)
    assert report.verdict is GCodeVerdict.BLOCKED
    assert any(i.code == "missing_file" for i in report.errors)


def test_a_real_file_round_trips(tmp_path):
    path = tmp_path / "cube.gcode"
    path.write_text(good(), encoding="utf-8")
    report = analyse_gcode_file(path, config=CONFIG, golden_profiles=GOLDEN)
    assert report.verdict is GCodeVerdict.SAFE


def test_binary_garbage_does_not_crash_the_analyser(tmp_path):
    path = tmp_path / "broken.gcode"
    path.write_bytes(b"\x00\x01\x02\xff\xfe not gcode at all")
    report = analyse_gcode_file(path, config=CONFIG)
    assert report.verdict is GCodeVerdict.BLOCKED


def test_the_report_serialises_for_the_api():
    payload = analyse(good()).as_dict()
    assert payload["verdict"] == "safe"
    assert payload["slicer"] == "PrusaSlicer"
    assert payload["bounds"]["max_x"] == 300.0
    assert payload["profile_status"] == "golden"


def test_a_foreign_file_cannot_claim_a_golden_profile_by_name():
    """A profile id is only a comment - trust needs the approved slicer too."""
    header = (
        ";Generated with Cura_SteamEngine 5.6.0\n"
        "; print_settings_id = Neptune3Plus 0.20 Standard\n"
    )
    report = analyse(good(header=header))
    assert report.verified_profile is False
    assert report.profile_status == "unverified"
    assert any(i.code == "non_prusaslicer" for i in report.warnings)
