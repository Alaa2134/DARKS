def test_acceleration_above_the_printer_config_warns():
    report = analyse(good("M204 S9000\n"))
    assert report.max_requested_accel == 9000
    assert any(i.code == "accel_above_printer" for i in report.warnings)


def test_acceleration_within_the_printer_config_is_fine():
    report = analyse(good("M204 S2500\n"))
    assert not any(i.code == "accel_above_printer" for i in report.issues)


def test_set_velocity_limit_is_understood():
    report = analyse(good("SET_VELOCITY_LIMIT ACCEL=5000 VELOCITY=400\n"))
    assert report.max_requested_accel == 5000
    assert report.max_requested_feedrate == pytest.approx(400 * 60)
    assert any(i.code == "accel_above_printer" for i in report.warnings)
    assert any(i.code == "feedrate_above_printer" for i in report.warnings)


def test_feedrate_above_the_printer_config_warns():
    report = analyse(good("G1 X20 Y20 F30000\n"))
    assert any(i.code == "feedrate_above_printer" for i in report.warnings)


