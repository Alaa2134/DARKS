def test_m413_is_reported_as_unsupported():
    report = analyse(good("M413 S1\n"))
    assert report.verdict is GCodeVerdict.WARNING
    assert any(u["command"] == "M413" for u in report.unsupported)
    issue = next(i for i in report.issues if i.code == "unsupported_command")
    assert "power-loss" in issue.detail.lower()


def test_g29_is_flagged_because_klipper_uses_bed_mesh_calibrate():
    report = analyse(good("G29\n"))
    assert any(u["command"] == "G29" for u in report.unsupported)


def test_each_unsupported_command_is_reported_once_not_per_line():
    report = analyse(good("M413 S1\n" * 50))
    assert len([i for i in report.issues if i.code == "unsupported_command"]) == 1


def test_supported_commands_are_not_flagged():
    report = analyse(good("M204 S2000\nM205 X8 Y8\nM220 S100\nM221 S95\nM486 S0\n"))
    assert report.unsupported == []


