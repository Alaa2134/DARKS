def test_cura_output_is_marked_unverified():
    header = ";Generated with Cura_SteamEngine 5.6.0\n;Layer height: 0.2\n"
    report = analyse(good(header=header))
    assert report.slicer == "Cura"
    assert report.verified_profile is False
    assert report.profile_status == "unverified"
    issue = next(i for i in report.issues if i.code == "non_prusaslicer")
    assert "UNVERIFIED G-CODE" in issue.message


def test_an_unrecognised_slicer_is_marked_unverified():
    report = analyse(good(header="; some random exporter\n"))
    assert report.slicer == ""
    assert any(i.code == "unknown_slicer" for i in report.warnings)


def test_prusaslicer_with_a_non_golden_profile_warns():
    header = HEADER.replace("Neptune3Plus 0.20 Standard", "Experimental 0.28 Draft")
    report = analyse(good(header=header))
    assert report.profile_status == "known"
    assert report.verified_profile is False
    assert any(i.code == "unverified_profile" for i in report.warnings)


def test_provenance_alone_never_blocks_a_geometrically_valid_file():
    """Unverified is a warning, not a block - the user decides."""
    report = analyse(good(header=";Generated with Cura_SteamEngine 5.6.0\n"))
    assert report.verdict is GCodeVerdict.WARNING
    assert report.blocked is False


