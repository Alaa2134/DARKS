def test_write_override_ini_is_sorted_and_readable(tmp_path: Path):
    path = write_override_ini(tmp_path / "o.ini", {"b": "2", "a": "1"})
    lines = [line for line in path.read_text().splitlines() if not line.startswith("#")]
    assert lines == ["a = 1", "b = 2"]
    values, _, _ = parse_ini(path.read_text())
    assert values == {"a": "1", "b": "2"}


