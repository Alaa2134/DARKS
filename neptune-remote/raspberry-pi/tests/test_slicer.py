def test_shipped_profiles_load():
    store = ProfileStore(PROFILES_DIR)
    printers = {p.id for p in store.list("printer")}
    filaments = {p.id for p in store.list("filament")}
    prints = {p.id for p in store.list("print")}

    assert {"neptune3plus_0.2", "neptune3plus_0.4", "neptune3plus_0.6", "neptune3plus_0.8"} <= printers
    assert {"pla", "pla_plus", "petg", "tpu", "asa", "abs", "custom"} <= filaments
    assert {"quality", "standard", "fast", "klipper_fast", "custom"} <= prints


def test_neptune_printer_profile_matches_the_hardware():
    store = ProfileStore(PROFILES_DIR)
    profile = store.require("printer", "neptune3plus_0.4")
    assert profile.values["bed_shape"] == "0x0,320x0,320x320,0x320"
    assert profile.values["max_print_height"] == "400"
    assert profile.values["nozzle_diameter"] == "0.4"
    assert profile.values["gcode_flavor"] == "klipper"
    assert "300x300" in profile.values["thumbnails"]
    assert profile.name.startswith("Elegoo Neptune 3 Plus")


