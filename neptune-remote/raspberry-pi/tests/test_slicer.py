class TestSlicerVerification:
    """A slicer that exists but cannot run must not report itself available.

    PrusaSlicer aborts at startup when the inherited locale has not been
    generated on the host - the default state of a fresh Raspberry Pi OS image,
    and also what happens when an SSH client forwards a locale the Pi lacks.
    Checking only that the binary exists reported slicing as working and let the
    failure surface later, deep inside a job.
    """

    def test_environment_pins_a_locale_that_always_exists(self, tmp_path):
        from app.slicer.engine import PrusaSlicerEngine
        from app.slicer.profiles import ProfileStore

        engine = PrusaSlicerEngine("prusa-slicer", ProfileStore(tmp_path))
        env = engine.subprocess_env()
        assert env["LC_ALL"] == "C"
        assert env["LANG"] == "C"
        # Still headless, and still able to find its own libraries.
        assert env["QT_QPA_PLATFORM"] == "offscreen"
        assert "PATH" in env

    async def test_missing_binary_verifies_false_with_a_reason(self, tmp_path):
        from app.slicer.engine import PrusaSlicerEngine
        from app.slicer.profiles import ProfileStore

        engine = PrusaSlicerEngine("definitely-not-a-real-slicer", ProfileStore(tmp_path))
        assert await engine.verify() is False
        assert "not found" in engine.verify_error.lower()

    async def test_binary_that_exits_nonzero_verifies_false(self, tmp_path):
        """Stands in for the locale crash: present, executable, dies at once."""
        from app.slicer.engine import PrusaSlicerEngine
        from app.slicer.profiles import ProfileStore

        broken = tmp_path / "broken-slicer"
        broken.write_text(
            "#!/bin/sh\n"
            "echo 'An error occured while setting up locale.' >&2\n"
            "echo 'locale::facet::_S_create_c_locale name not valid' >&2\n"
            "exit 2\n"
        )
        broken.chmod(0o755)

        engine = PrusaSlicerEngine(str(broken), ProfileStore(tmp_path))
        assert engine.available is True, "the file is there"
        assert await engine.verify() is False, "but it cannot run"
        assert "locale" in engine.verify_error.lower()

    async def test_verification_is_cached(self, tmp_path):
        from app.slicer.engine import PrusaSlicerEngine
        from app.slicer.profiles import ProfileStore

        counter = tmp_path / "counter"
        script = tmp_path / "counting-slicer"
        script.write_text(f"#!/bin/sh\necho x >> {counter}\nexit 0\n")
        script.chmod(0o755)

        engine = PrusaSlicerEngine(str(script), ProfileStore(tmp_path))
        assert await engine.verify() is True
        assert await engine.verify() is True
        assert counter.read_text().count("x") == 1, "cached after the first run"

        await engine.verify(force=True)
        assert counter.read_text().count("x") == 2


class TestSupportPlacement:
    """Where support may start from, which the app could not express at all.

    Style - grid, snug, organic - is the shape of the support and the less
    consequential of the two choices. Support that grows off the model marks
    whatever surface it stood on, and no style setting undoes that.
    """

    def _request(self, **kwargs):
        from app.schemas import SliceRequest

        return SliceRequest(model_id="m", supports=True, **kwargs)

    def test_build_plate_only_reaches_prusa(self):
        from app.slicer.engine import build_prusa_overrides

        out = build_prusa_overrides(self._request(support_placement="build_plate_only"))
        assert out["support_material_buildplate_only"] == "1"

    def test_everywhere_is_sent_explicitly_rather_than_left_to_a_default(self):
        from app.slicer.engine import build_prusa_overrides

        out = build_prusa_overrides(self._request(support_placement="everywhere"))
        assert out["support_material_buildplate_only"] == "0"

    def test_orca_gets_its_own_key_names(self):
        from app.slicer.engine import build_orca_overrides

        out = build_orca_overrides(
            self._request(support_placement="build_plate_only", support_threshold_angle=55)
        )
        assert out["support_on_build_plate_only"] is True
        assert out["support_threshold_angle"] == 55

    def test_nothing_support_related_is_sent_when_support_is_off(self):
        from app.schemas import SliceRequest
        from app.slicer.engine import build_prusa_overrides

        out = build_prusa_overrides(
            SliceRequest(
                model_id="m",
                supports=False,
                support_placement="build_plate_only",
                support_threshold_angle=55,
            )
        )
        assert out["support_material"] == "0"
        assert "support_material_buildplate_only" not in out
        assert "support_material_threshold" not in out

    def test_an_unset_angle_leaves_the_engine_default_alone(self):
        from app.slicer.engine import build_prusa_overrides

        out = build_prusa_overrides(self._request())
        assert "support_material_threshold" not in out


class TestExpandedOptions:
    """The settings the app could not express, and what "unset" has to mean.

    Every one of these is optional, and the rule throughout is that a value
    the user never chose is never sent: overriding a printer profile silently
    is worse than not offering the setting at all.
    """

    def _request(self, **kwargs):
        from app.schemas import SliceRequest

        return SliceRequest(model_id="m", **kwargs)

    def test_nothing_extra_is_sent_when_nothing_was_chosen(self):
        from app.slicer.engine import build_prusa_overrides

        out = build_prusa_overrides(self._request())
        for key in (
            "top_solid_layers", "bottom_solid_layers", "ironing", "seam_position",
            "spiral_vase", "retract_lift", "min_fan_speed", "max_fan_speed",
            "disable_fan_first_layers", "avoid_crossing_perimeters", "fill_pattern",
        ):
            assert key not in out, key

    def test_shell_and_surface_reach_prusa(self):
        from app.slicer.engine import build_prusa_overrides

        out = build_prusa_overrides(
            self._request(
                top_solid_layers=5,
                bottom_solid_layers=4,
                seam_position="rear",
                infill_pattern="gyroid",
                retraction_z_hop=0.4,
            )
        )
        assert out["top_solid_layers"] == "5"
        assert out["bottom_solid_layers"] == "4"
        assert out["seam_position"] == "rear"
        assert out["fill_pattern"] == "gyroid"
        assert out["retract_lift"] == "0.4"

    def test_booleans_use_each_engines_own_spelling(self):
        """Orca does not have an on/off ironing flag; it names the surfaces."""
        from app.slicer.engine import build_orca_overrides, build_prusa_overrides

        request = self._request(ironing=True, spiral_vase=True, avoid_crossing_perimeters=True)
        prusa = build_prusa_overrides(request)
        orca = build_orca_overrides(request)

        assert prusa["ironing"] == "1"
        assert prusa["spiral_vase"] == "1"
        assert prusa["avoid_crossing_perimeters"] == "1"

        assert orca["ironing_type"] == "top"
        assert orca["spiral_mode"] is True
        assert orca["reduce_crossing_wall"] is True

    def test_ironing_off_is_sent_as_off_not_omitted(self):
        """False is a choice; None is not. They must not collapse together."""
        from app.slicer.engine import build_orca_overrides, build_prusa_overrides

        request = self._request(ironing=False)
        assert build_prusa_overrides(request)["ironing"] == "0"
        assert build_orca_overrides(request)["ironing_type"] == "no ironing"

    def test_cooling_reaches_both_engines(self):
        from app.slicer.engine import build_orca_overrides, build_prusa_overrides

        request = self._request(
            fan_min_percent=30, fan_max_percent=100, disable_fan_first_layers=2
        )
        prusa = build_prusa_overrides(request)
        orca = build_orca_overrides(request)
        assert prusa["min_fan_speed"] == "30"
        assert prusa["disable_fan_first_layers"] == "2"
        assert orca["fan_max_speed"] == 100
        assert orca["close_fan_the_first_x_layers"] == 2

    def test_raw_overrides_still_win_over_everything(self):
        from app.slicer.engine import build_prusa_overrides

        out = build_prusa_overrides(
            self._request(top_solid_layers=5, custom_overrides={"top_solid_layers": "9"})
        )
        assert out["top_solid_layers"] == "9"
