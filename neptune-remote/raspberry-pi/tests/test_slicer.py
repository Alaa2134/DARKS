def test_parse_duration_variants():
    assert parse_duration("1h 24m 13s") == 5053
    assert parse_duration("2d 1h") == 176400
    assert parse_duration("45s") == 45
    assert parse_duration("3600") == 3600
    assert parse_duration("") is None
    assert parse_duration("soon") is None


def test_parse_gcode_extracts_stats(tmp_path: Path):
    path = tmp_path / "out.gcode"
    path.write_text(SAMPLE_GCODE, encoding="utf-8")
    meta = parse_gcode(path)
    assert meta["estimated_time"] == 5053
    assert meta["filament_grams"] == pytest.approx(12.88)
    assert meta["filament_mm"] == pytest.approx(4321.5)
    assert meta["filament_cm3"] == pytest.approx(10.39)
    assert meta["layer_count"] == 118
    assert meta["layer_height"] == pytest.approx(0.2)
    assert meta["filament_type"] == "PLA"
    assert "PrusaSlicer" in str(meta["slicer"])
    assert meta["gcode_size"] > 0


def test_stats_from_gcode_converts_to_meters(tmp_path: Path):
    path = tmp_path / "out.gcode"
    path.write_text(SAMPLE_GCODE, encoding="utf-8")
    stats = stats_from_gcode(path)
    assert stats.filament_meters == pytest.approx(4.3215)
    assert stats.filament_grams == pytest.approx(12.88)
    assert stats.estimated_time_seconds == 5053
    assert stats.layer_count == 118


def test_layer_count_falls_back_to_layer_changes(tmp_path: Path):
    path = tmp_path / "out.gcode"
    path.write_text(SAMPLE_GCODE.replace("; total layers count = 118", ""), encoding="utf-8")
    assert parse_gcode(path)["layer_count"] == 3


def test_parse_gcode_of_missing_file_is_empty(tmp_path: Path):
    assert parse_gcode(tmp_path / "nope.gcode") == {}


