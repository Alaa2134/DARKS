@pytest.mark.asyncio
async def test_job_manager_reports_a_missing_slicer_as_a_failed_job(tmp_path: Path):
    models = ModelStore(tmp_path / "models")
    gcodes = GCodeStore(tmp_path / "gcode")
    model = models.save("cube.stl", b"solid cube\nendsolid cube\n")

    engine = PrusaSlicerEngine("definitely-not-installed-slicer", ProfileStore(PROFILES_DIR), 30)
    manager = SliceJobManager(engine, models, gcodes)

    seen: list[str] = []

    async def listener(job):
        seen.append(job.status)

    manager.add_listener(listener)
    job = manager.submit(SliceRequest(model_id=model.id))
    for _ in range(50):
        await asyncio.sleep(0.02)
        if job.status in {"failed", "done"}:
            break

    assert job.status == "failed"
    assert "not found" in (job.error or "")
    assert "failed" in seen


