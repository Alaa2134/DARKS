def test_preflight_produces_the_pre_print_banner(client: TestClient):
    body = client.get("/api/gcode/preflight", params={"filename": "cube.gcode"}).json()
    banner = body["banner"]
    assert banner["slicer"] == "PrusaSlicer"
    assert banner["build_volume"] == "PASSED"
    assert banner["unsupported_commands"] == "NONE"
    assert body["verdict"] in {"ready", "warning"}


def test_strict_mode_is_stricter(client: TestClient):
    lenient = client.get("/api/gcode/preflight", params={"filename": "cube.gcode"}).json()
    strict = client.get(
        "/api/gcode/preflight", params={"filename": "cube.gcode", "strict": "true"}
    ).json()
    assert strict["strict"] is True
    # Strict can only ever be the same or worse.
    order = {"ready": 0, "warning": 1, "blocked": 2}
    assert order[strict["verdict"]] >= order[lenient["verdict"]]


