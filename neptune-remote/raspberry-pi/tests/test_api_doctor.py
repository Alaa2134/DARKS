#: Commands the fake Moonraker was asked to run.
SENT: list[str] = []
#: Advancing clock for the fake console buffer.
STORE_TICK = [0]


def moonraker_handler(request: httpx.Request) -> httpx.Response:
    path = request.url.path

    if path == "/server/info":
        return httpx.Response(200, json={"result": {"klippy_state": "ready", "klippy_connected": True}})
    if path == "/printer/info":
        return httpx.Response(200, json={"result": {"state": "ready", "state_message": "Ready"}})
    if path == "/printer/objects/list":
        return httpx.Response(200, json={"result": {"objects": ["toolhead", "extruder"]}})
    if path == "/printer/objects/query":
        return httpx.Response(
            200,
            json={
                "result": {
                    "status": {
                        "print_stats": {"state": "standby", "filename": ""},
                        "toolhead": {"homed_axes": "xyz", "position": [10, 10, 5, 0]},
                        "extruder": {"temperature": 24.0, "target": 0.0},
                        "heater_bed": {"temperature": 23.0, "target": 0.0},
                        "mcu": {"mcu_version": "v0.12.0", "last_stats": {"mcu_task_avg": 0.002}},
                    }
                }
            },
        )
    if path == "/server/files/config/printer.cfg":
        return httpx.Response(200, content=PRINTER_CFG.encode())
    if path.startswith("/server/files/logs/"):
        return httpx.Response(200, content=b"Starting Klippy...\n")
    if path == "/printer/gcode/script":
        SENT.append(request.url.params.get("script", ""))
        return httpx.Response(200, json={"result": "ok"})
    if path == "/server/gcode_store":
        # Moonraker's buffer grows as commands run; the client reads whatever
        # appeared after the marker it noted, so the timestamps must advance.
        STORE_TICK[0] += 1
        return httpx.Response(
            200,
            json={
                "result": {
                    "gcode_store": [
                        {"time": float(STORE_TICK[0]), "message": "// probe: open"}
                    ]
                }
            },
        )
    if path == "/printer/firmware_restart":
        return httpx.Response(200, json={"result": "ok"})
    if path.startswith("/server/files/gcodes/"):
        return httpx.Response(200, content=GCODE.encode())
    if path == "/server/files/upload":
        return httpx.Response(200, json={"result": {"item": {"path": "printer.cfg"}}})
    return httpx.Response(200, json={"result": {}})


@pytest.fixture()
def client(tmp_path: Path):
    SENT.clear()
    STORE_TICK[0] = 0
    config = AppConfig()
    config.paths.data_dir = str(tmp_path / "data")
    config.paths.models_dir = str(tmp_path / "data" / "models")
    config.paths.gcode_dir = str(tmp_path / "data" / "gcode")
    config.paths.database = str(tmp_path / "data" / "neptune.db")
    config.paths.profiles_dir = str(PROFILES)
    config.storage.root = str(tmp_path / "printer_data" / "neptune_remote")
    config.storage.backup_sources = []
    config.power.provider = "demo"
    config.camera.stream_url = ""
    config.camera.snapshot_url = ""
    config.camera.device = ""

    app = create_app(config)
    with TestClient(app) as test_client:
        services = app.state.services
        services.moonraker._client = httpx.AsyncClient(
            transport=httpx.MockTransport(moonraker_handler), base_url="http://moonraker"
        )
        yield test_client


