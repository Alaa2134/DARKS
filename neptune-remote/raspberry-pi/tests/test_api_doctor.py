def test_the_inspector_reports_bounds_and_provenance(client: TestClient):
    body = client.get("/api/gcode/inspect", params={"filename": "cube.gcode"}).json()
    assert body["slicer"] == "PrusaSlicer"
    assert body["bounds"]["max_x"] == 300.0
