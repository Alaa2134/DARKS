def test_a_workflow_runs_step_by_step(client: TestClient):
    started = client.post("/api/doctor/workflows/start", json={"kind": "safe_home"}).json()
    assert started["state"] == "running"
    assert started["steps"][0]["id"] == "probe_check"

    advanced = client.post("/api/doctor/workflows/advance?force=true").json()
    assert advanced["steps"][0]["state"] == "done"
    assert "QUERY_PROBE" in SENT


def test_two_workflows_cannot_run_at_once(client: TestClient):
    client.post("/api/doctor/workflows/start", json={"kind": "safe_home"})
    response = client.post("/api/doctor/workflows/start", json={"kind": "bed_mesh"})
    assert response.status_code == 409


def test_cancelling_frees_the_runner(client: TestClient):
    client.post("/api/doctor/workflows/start", json={"kind": "safe_home"})
    client.post("/api/doctor/workflows/cancel")
    assert client.post("/api/doctor/workflows/start", json={"kind": "bed_mesh"}).status_code == 200


