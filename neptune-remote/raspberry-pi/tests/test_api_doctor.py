def test_a_slicer_profile_can_be_saved_and_pinned(client: TestClient):
    created = client.post(
        "/api/slicer/profiles",
        json={"name": "Neptune3Plus 0.20 Standard", "settings": {"layer_height": 0.2}},
    ).json()
    assert created["version"] == 1
    assert created["status"] == "candidate"

    pinned = client.post(f"/api/slicer/profiles/{created['id']}/golden").json()
    assert pinned["golden"] is True

    listing = client.get("/api/slicer/profiles").json()
    assert "Neptune3Plus 0.20 Standard" in listing["golden_names"]


def test_editing_a_golden_profile_creates_a_new_version(client: TestClient):
    created = client.post(
        "/api/slicer/profiles", json={"name": "P", "settings": {"accel": 3000}}
    ).json()
    client.post(f"/api/slicer/profiles/{created['id']}/golden")

    edited = client.post(
        "/api/slicer/profiles", json={"name": "P", "settings": {"accel": 6000}}
    ).json()
    assert edited["id"] != created["id"]
    assert edited["version"] == 2
    assert edited["golden"] is False


def test_a_golden_profile_cannot_be_deleted_through_the_api(client: TestClient):
    created = client.post("/api/slicer/profiles", json={"name": "P", "settings": {}}).json()
    client.post(f"/api/slicer/profiles/{created['id']}/golden")
    assert client.delete(f"/api/slicer/profiles/{created['id']}").status_code == 409


def test_a_golden_profile_makes_matching_gcode_verified(client: TestClient):
    created = client.post(
        "/api/slicer/profiles",
        json={"name": "Neptune3Plus 0.20 Standard", "settings": {}},
    ).json()
    client.post(f"/api/slicer/profiles/{created['id']}/golden")

    body = client.get("/api/gcode/inspect", params={"filename": "cube.gcode"}).json()
    assert body["profile_status"] == "golden"
    assert body["verified_profile"] is True
