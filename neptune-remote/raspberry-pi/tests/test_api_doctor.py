def test_evaluating_a_command_sends_nothing(client: TestClient):
    body = client.post(
        "/api/doctor/command/evaluate", json={"command": "G1 X400 Y10"}
    ).json()
    assert body["kind"] == "movement"
    assert "X330" in body["command"]        # clamped to the live config
    assert SENT == []


def test_a_blocked_command_returns_409_and_is_never_sent(client: TestClient):
    client.post("/api/doctor/probe/query")
    SENT.clear()
    # TESTZ without a calibration session is blocked.
    response = client.post("/api/doctor/command/execute", json={"command": "TESTZ Z=-0.05"})
    assert response.status_code == 409
    detail = response.json()["detail"]
    assert detail["severity"] == "blocked"
    assert any(i["code"] == "no_calibration_session" for i in detail["issues"])
    assert SENT == []


def test_an_allowed_command_is_sent_after_clamping(client: TestClient):
    client.post("/api/doctor/probe/query")
    SENT.clear()
    body = client.post(
        "/api/doctor/command/execute", json={"command": "G1 X400 Y10", "force": True}
    ).json()
    assert body["allowed"] is True
    assert "X330" in SENT[-1]


def test_the_audit_log_records_decisions(client: TestClient):
    client.post("/api/doctor/probe/query")
    client.post("/api/doctor/command/execute", json={"command": "G1 X10", "force": True})
    entries = client.get("/api/doctor/command/audit").json()["entries"]
    assert any(e["original"] == "G1 X10" for e in entries)


