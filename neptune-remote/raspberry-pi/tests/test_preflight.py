def healthy_report():
    return DiagnosticsEngine(profile=NEPTUNE_3_PLUS).run(
        DiagnosticInput(
            moonraker_reachable=True,
            klippy_state="ready",
            config=CONFIG,
            homed_axes="xyz",
            probe_triggered=False,
            mcu_awake=True,
            heaters={"extruder": {"temperature": 24.0, "target": 0.0}},
            disk_free_gb=30.0,
        )
    )


def test_a_healthy_printer_with_clean_gcode_is_ready():
    gcode = analyse_gcode(
        GOOD_GCODE, config=CONFIG, golden_profiles=["Neptune3Plus 0.20 Standard"]
    )
    report = run_preflight(health=healthy_report(), gcode=gcode)
    assert report.verdict == "ready"
    assert report.ready is True


def test_a_gcode_error_blocks_the_print():
    gcode = analyse_gcode(
        GOOD_GCODE + "G1 X500 Y10\n", config=CONFIG, golden_profiles=["Neptune3Plus 0.20 Standard"]
    )
    report = run_preflight(health=healthy_report(), gcode=gcode)
    assert report.verdict == "blocked"
    assert any(c.id.startswith("gcode_outside_build_volume") for c in report.failures)


def test_a_critical_printer_finding_blocks_the_print():
    health = DiagnosticsEngine(profile=NEPTUNE_3_PLUS).run(
        DiagnosticInput(
            moonraker_reachable=True,
            klippy_state="ready",
            config=CONFIG,
            probe_triggered=True,
            mcu_awake=True,
        )
    )
    gcode = analyse_gcode(GOOD_GCODE, config=CONFIG, golden_profiles=["Neptune3Plus 0.20 Standard"])
    report = run_preflight(health=health, gcode=gcode)
    assert report.verdict == "blocked"


def test_strict_mode_turns_warnings_into_blocks():
    gcode = analyse_gcode(GOOD_GCODE + "M413 S1\n", config=CONFIG, golden_profiles=[])
    lenient = run_preflight(health=healthy_report(), gcode=gcode, strict=False)
    strict = run_preflight(health=healthy_report(), gcode=gcode, strict=True)
    assert lenient.verdict == "warning"
    assert strict.verdict == "blocked"


def test_a_missing_gcode_analysis_is_an_error_not_a_pass():
    report = run_preflight(health=healthy_report(), gcode=None)
    assert report.verdict == "blocked"
    assert any(c.id == "gcode_validation" for c in report.failures)


def test_an_unchecked_printer_warns_rather_than_passing():
    gcode = analyse_gcode(GOOD_GCODE, config=CONFIG, golden_profiles=["Neptune3Plus 0.20 Standard"])
    report = run_preflight(health=None, gcode=gcode)
    assert report.verdict == "warning"


def test_the_banner_reports_every_field_from_the_brief():
    gcode = analyse_gcode(GOOD_GCODE, config=CONFIG, golden_profiles=["Neptune3Plus 0.20 Standard"])
    banner = run_preflight(health=healthy_report(), gcode=gcode).banner
    assert banner["slicer"] == "PrusaSlicer"
    assert banner["printer_profile"] == "Neptune3Plus 0.20 Standard"
    assert banner["profile_status"] == "GOLDEN"
    assert banner["gcode_validation"] == "SAFE"
    assert banner["build_volume"] == "PASSED"
    assert banner["unsupported_commands"] == "NONE"
    assert banner["motion_limits"] == "PASSED"


def test_the_banner_names_the_unsupported_commands_it_found():
    gcode = analyse_gcode(GOOD_GCODE + "M413 S1\n", config=CONFIG, golden_profiles=[])
    banner = run_preflight(health=healthy_report(), gcode=gcode).banner
    assert "M413" in banner["unsupported_commands"]


def test_unverified_gcode_is_surfaced_in_the_banner():
    cura = GOOD_GCODE.replace("; generated by PrusaSlicer 2.8.1+linux", ";Generated with Cura_SteamEngine 5.6")
    gcode = analyse_gcode(cura, config=CONFIG, golden_profiles=["Neptune3Plus 0.20 Standard"])
    report = run_preflight(health=healthy_report(), gcode=gcode)
    assert report.banner["profile_status"] == "UNVERIFIED"
    assert report.verdict == "warning"


def test_a_filament_shortage_warns_without_blocking():
    gcode = analyse_gcode(GOOD_GCODE, config=CONFIG, golden_profiles=["Neptune3Plus 0.20 Standard"])
    report = run_preflight(
        health=healthy_report(), gcode=gcode,
        filament_ok=False, filament_message="Only 12 g left",
    )
    assert report.verdict == "warning"
    assert any(c.id == "filament" for c in report.warnings)


def test_the_report_serialises_for_the_api():
    gcode = analyse_gcode(GOOD_GCODE, config=CONFIG, golden_profiles=["Neptune3Plus 0.20 Standard"])
    payload = run_preflight(health=healthy_report(), gcode=gcode).as_dict()
    assert payload["verdict"] == "ready"
    assert payload["banner"]["slicer"] == "PrusaSlicer"
    assert payload["gcode"]["slicer"] == "PrusaSlicer"
