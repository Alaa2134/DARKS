@pytest.fixture()
def profiles(tmp_path):
    from app.db import Database

    db = Database(tmp_path / "profiles.db")
    yield GoldenProfileStore(db)
    db.close()


def test_saving_the_same_name_creates_a_new_version(profiles):
    first = profiles.save("Neptune3Plus 0.20", {"layer_height": 0.2})
    second = profiles.save("Neptune3Plus 0.20", {"layer_height": 0.24})
    assert first.version == 1
    assert second.version == 2
    assert second.parent_id == first.id


def test_saving_identical_settings_does_not_create_a_version(profiles):
    first = profiles.save("P", {"layer_height": 0.2})
    again = profiles.save("P", {"layer_height": 0.2})
    assert again.id == first.id
    assert len(profiles.versions_of("P")) == 1


def test_editing_a_golden_profile_never_overwrites_it(profiles):
    """The whole point of pinning: convenience must not touch the known-good one."""
    original = profiles.save("Golden N3P", {"layer_height": 0.2, "accel": 3000})
    profiles.mark_golden(original.id)

    edited = profiles.save("Golden N3P", {"layer_height": 0.2, "accel": 6000})

    assert edited.id != original.id
    assert edited.golden is False
    stored = profiles.get(original.id)
    assert stored.golden is True
    assert stored.settings["accel"] == 3000      # untouched


def test_a_golden_profile_cannot_be_deleted(profiles):
    profile = profiles.save("P", {"a": 1})
    profiles.mark_golden(profile.id)
    assert profiles.delete(profile.id) is False
    assert profiles.get(profile.id) is not None


def test_a_candidate_profile_can_be_deleted(profiles):
    profile = profiles.save("P", {"a": 1})
    assert profiles.delete(profile.id) is True


def test_promoting_a_new_version_demotes_the_previous_golden_for_that_name(profiles):
    first = profiles.save("P", {"a": 1})
    profiles.mark_golden(first.id)
    second = profiles.save("P", {"a": 2})
    profiles.mark_golden(second.id)
    assert profiles.get(first.id).golden is False
    assert profiles.get(second.id).golden is True


def test_golden_is_per_profile_name_not_global(profiles):
    a = profiles.save("Draft", {"a": 1})
    b = profiles.save("Fine", {"b": 1})
    profiles.mark_golden(a.id)
    profiles.mark_golden(b.id)
    assert {p.name for p in profiles.golden_profiles()} == {"Draft", "Fine"}


def test_print_outcomes_are_recorded(profiles):
    profile = profiles.save("P", {"a": 1})
    profiles.record_print(profile.id, success=True)
    profiles.record_print(profile.id, success=False)
    updated = profiles.get(profile.id)
    assert updated.successful_prints == 1
    assert updated.failed_prints == 1


def test_golden_names_feed_the_gcode_validator(profiles):
    profile = profiles.save("Neptune3Plus 0.20 Standard", {"a": 1})
    profiles.mark_golden(profile.id)
    report = analyse_gcode(GOOD_GCODE, config=CONFIG, golden_profiles=profiles.golden_names())
    assert report.verified_profile is True
    assert report.profile_status == "golden"


