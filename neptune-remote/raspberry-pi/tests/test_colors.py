def test_a_name_cannot_end_the_gcode_line_early():
    """A semicolon in a colour name would comment out the rest of the command."""
    assert clean_color_name('red; M112') == "red M112"
    assert '"' not in clean_color_name('re"d')


def test_the_plan_is_readable_back_from_the_file(tmp_path):
    path = write(tmp_path, PRUSA)
    apply_color_changes(path, [(2, "أحمر"), (4, "أزرق")])
    plan = parse_manifest(path.read_text(encoding="utf-8"))
    assert [(c.layer, c.color) for c in plan] == [(2, "أحمر"), (4, "أزرق")]


def test_a_file_with_no_plan_reads_back_as_empty():
    assert parse_manifest(PRUSA) == []


def test_the_paused_colour_comes_from_the_display_message():
    assert color_from_display("COLOR: أحمر") == "أحمر"
    assert color_from_display("Printing 40%") is None
    assert color_from_display("") is None


