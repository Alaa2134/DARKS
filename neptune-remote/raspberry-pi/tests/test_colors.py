# The macro
# --------------------------------------------------------------------------- #

BED_SLINGER = """
[pause_resume]

[stepper_x]
position_min: -8.3
position_max: 330

[stepper_y]
position_min: -1.3
position_max: 330

[stepper_z]
position_max: 400

[extruder]
min_extrude_temp: 170
"""


def test_pause_comes_before_the_parking_moves():
    """The single most consequential line order in the macro.

    [pause_resume] records where the toolhead is when PAUSE runs, and RESUME
    returns there. Park first and the print resumes from the parking corner.
    """
    suggestion = suggest_color_change(parse_config(BED_SLINGER))
    assert suggestion.ok
    body = suggestion.gcode
    assert body.index("\n    PAUSE") < body.index("G1 E-")
    assert body.index("\n    PAUSE") < body.index("G1 X")


def test_the_macro_announces_the_colour_before_it_stops():
    body = suggest_color_change(parse_config(BED_SLINGER)).gcode
    assert body.index("M117 COLOR:") < body.index("\n    PAUSE")


def test_the_macro_parks_inside_the_configured_travel():
    body = suggest_color_change(parse_config(BED_SLINGER)).gcode
    # position_min is negative here - homing overtravel, not bed - so the park
    # must be measured from the bed origin.
    assert "G1 X5.0 Y5.0" in body


def test_without_pause_resume_the_macro_is_refused():
    suggestion = suggest_color_change(parse_config("[extruder]\nmin_extrude_temp: 170\n"))
    assert not suggestion.ok
    assert "pause_resume" in suggestion.blockers[0]
    assert suggestion.gcode == ""


def test_an_existing_macro_is_reported_rather_than_overwritten():
    config = parse_config(BED_SLINGER + "\n[gcode_macro COLOR_CHANGE]\ngcode:\n    M117 hi\n")
    assert has_color_change_macro(config)
    assert suggest_color_change(config).conflicts


def test_a_printer_without_the_macro_says_so():
    assert not has_color_change_macro(parse_config(BED_SLINGER))
